#!/usr/bin/env bash
# Every `allow`/`expect` of `clippy::disallowed_types` under `src/` must carry a
# tag that either names the type-ladder PR retiring that raw use of a Candid
# boundary type or declares the use permanent with a reason. The tag is a line
# comment directly above the attribute's opening line
#     // disallowed-types: removed by <PR>
#     // disallowed-types: permanent, <why>
# or, equivalently, a `reason` string inside the attribute, which survives
# rustfmt reordering a neighbouring `use`/`mod` item between a comment and the
# item it belonged to (preferred above `use` items)
#     #[allow(clippy::disallowed_types, reason = "disallowed-types: removed by <PR>")]
# `<PR>` is one token (a ladder step such as `B2` or `A2.1`, `#1234`, or a PR
# URL). The banned types are listed in `src/internet_identity/clippy.toml`.
#
# How the scan works, so that formatting cannot hide an attribute:
# - Comments, string literals and char literals are blanked out (newlines and
#   byte offsets kept) before attributes are matched, so a delimiter inside
#   them cannot cut an attribute short and text inside them is never scanned.
# - Tags are looked up in a second view in which line comments are kept but
#   strings, char literals and block comments are still blanked, so a string
#   or block comment whose last line looks like a tag does not count as one.
#   A reason-string tag counts only when the `reason` identifier is live code
#   in the attribute and its value is a string literal, so the same text in a
#   comment or inside another string does not count either.
# - The five non-ASCII characters rustc treats as whitespace (U+0085, U+200E,
#   U+200F, U+2028, U+2029) are normalised to spaces first.
# - `#`, `!` and `[` are separate tokens and may be separated by whitespace or
#   comments; brackets and parentheses are matched balanced; every
#   `allow`/`expect` list inside an attribute is inspected.
# - The lint may be named with or without the `clippy::` tool prefix (rustc
#   still resolves the bare name), by its pre-1.62 name `disallowed_type`, as
#   raw identifiers, or through a group that contains it (`clippy::style`,
#   `clippy::all`, the deprecated `clippy_style`/`clippy_all` aliases, and bare
#   `warnings`, which silences it whenever clippy runs without `-D clippy::all`).
# - A macro metavariable inside an allow list (`#[allow(clippy::$lint)]`) may
#   expand to the lint and therefore needs a tag too.
# So an untagged allow written in any of these forms is rejected:
#     #[allow(dead_code, clippy::disallowed_types)]
#     #[expect(clippy::disallowed_types)]
#     #[allow(clippy::style)]            #[allow(clippy::all)]
#     #[allow(clippy :: disallowed_types)]
#     #[allow(clippy::disallowed_types, reason = "legacy [B2]")]
#     #[allow(clippy::r#disallowed_types)]
#     #[allow(renamed_and_removed_lints, disallowed_types)]
#     # [allow(clippy::disallowed_types)]
#     # /* note */ [allow(clippy::disallowed_types)]
#     #[cfg_attr(test, allow(dead_code), allow(clippy::disallowed_types))]
#     #[allow(
#         // see [B2]
#         clippy::disallowed_types,
#     )]
# and an attribute quoted inside a comment or a string is not an attribute.
# `warn`/`deny`/`forbid` never need a tag.
#
# Known limits of a source scan, none of which the tree uses today: nested
# block comments (`/* /* */ */`) are not understood; an attribute inside a
# `macro_rules!` body is checked as if it were live even when the macro is
# never invoked; an attribute assembled by a macro from a whole-attribute
# metavariable (`#[$attr]`), injected by a proc macro, generated by a build
# script, or living in a file that is not `*.rs` (`#[path = "m.txt"]`,
# `include!("x.in")`) or outside `src/` is invisible.
# `scripts/check-disallowed-types-tags.test.sh` pins all of the above.
#
# Usage: check-disallowed-types-tags.sh [DIR]   (DIR defaults to src/)
set -euo pipefail
cd "$(dirname "$0")/.."
dir="${1:-src}"

status=0
while IFS= read -r -d '' file; do
    if ! perl -0777 -ne '
        my $bad = 0;
        # Lexical tokens that may contain delimiters or attribute-like text.
        my $tokens = qr{
              //[^\n]*                                   # line comment
            | /\*(?:(?!\*/).)*\*/                        # block comment
            | b?r(\#*)"(?:(?!"\1).)*"\1                  # raw string
            | b?"(?:[^"\\]|\\.)*"                        # string
            | b?\x27(?:[^\x27\\\n][\x80-\xBF]*|\\x[0-9A-Fa-f]{2}|\\u\{[0-9A-Fa-f_]{1,6}\}|\\.)\x27   # char literal (one UTF-8 char)
        }xs;
        # View for finding attributes: every token blanked, newlines and byte
        # offsets kept.
        (my $code = $_) =~ s{$tokens}{ (my $blank = $&) =~ s/[^\n]/ /g; $blank }ge;
        # Whitespace rustc accepts that the byte-mode \s below does not.
        $code =~ s/\xC2\x85|\xE2\x80[\x8E\x8F\xA8\xA9]/" " x length($&)/ge;
        # View for finding tags: line comments kept, every other token blanked.
        (my $tags = $_) =~ s{$tokens}{ substr($&, 0, 2) eq "//" ? $& : do { (my $blank = $&) =~ s/[^\n]/ /g; $blank } }ge;
        my @lines = split /\n/, $tags, -1;
        # View for reading reason strings: string literals kept, comments and
        # char literals blanked.
        (my $strs = $_) =~ s{$tokens}{ my $m = $&; $m =~ /^b?(?:r\#*)?"/ ? $m : do { (my $blank = $m) =~ s/[^\n]/ /g; $blank } }ge;
        my $pr = qr{[A-Za-z0-9.#/:-]+};
        # Each attribute, outer or inner, as a whole (brackets balanced).
        while ($code =~ /#\s*!?\s*\[((?:[^\[\]]++|\[(?1)\])*)\]/gs) {
            my ($attr, $start, $end) = ($1, $-[0], $+[0]);
            my $hit = 0;
            # Every allow/expect list inside it (parentheses balanced).
            while ($attr =~ /\b(?:r\#)?(?:allow|expect)\s*(\((?:[^()]++|(?1))*\))/gs) {
                # Each comma-separated item as a whole path, with whitespace
                # (comments are already blanked) and raw-identifier prefixes
                # removed, so `rustdoc :: all` is not mistaken for bare `all`.
                for my $item (split /,/, substr($1, 1, -1)) {
                    (my $path = $item) =~ s/\s+//g;
                    $path =~ s/r#//g;
                    $hit = 1 if $path =~ /^(?:clippy::)?(?:disallowed_types?|style|all)$/;
                    $hit = 1 if $path =~ /^(?:clippy_(?:style|all)|warnings)$/;
                    $hit = 1 if $item =~ /\$/;
                }
            }
            next unless $hit;
            my $line = 1 + (substr($code, 0, $start) =~ tr/\n//);
            my $prev = $line > 1 ? $lines[$line - 2] : "";
            $prev =~ s/\r$//;
            next if $prev =~ m{^\s*//\s*disallowed-types: (?:removed by $pr|permanent, \S.*?)\s*$};
            # The reason-string form: `reason` must be live code in the
            # attribute (not comment or string contents) and its value a
            # string literal, plain or raw.
            my ($live, $withstrs) = (substr($code, $start, $end - $start), substr($strs, $start, $end - $start));
            my $tagged = 0;
            while ($withstrs =~ /\breason\s*=\s*(?:r(\#*)"((?:(?!"\1).)*)"\1|"((?:[^"\\]|\\.)*)")/gs) {
                next unless substr($live, $-[0], 6) eq "reason";
                my $text = defined $2 ? $2 : $3;
                $tagged = 1 if $text =~ m{^disallowed-types: (?:removed by $pr|permanent, \S.*?)\s*$};
            }
            next if $tagged;
            print STDERR "$ARGV:$line: allow/expect of clippy::disallowed_types (or a lint group containing it: clippy::style, clippy::all, warnings) without a \x27// disallowed-types: ...\x27 tag on the line above or a reason = \"disallowed-types: ...\" string\n";
            $bad = 1;
        }
        exit $bad;
    ' "$file"; then
        status=1
    fi
done < <(find "$dir" -iname '*.rs' \( -type f -o -type l \) -print0 | sort -z)

if [ "$status" -eq 0 ]; then
    echo "disallowed-types allow tags: ok"
fi
exit "$status"
